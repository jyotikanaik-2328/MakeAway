    function translate(value, language) {
        const normalized = value.trim().replace(/\s+/g, " ");
        if (!normalized) return normalized;
        if (language === "kn") {
            if (kannada[normalized]) return kannada[normalized];
            if (festivalNameTranslations[normalized]) return festivalNameTranslations[normalized];
            const festivalYear = normalized.match(/^Festival fare dates for (\d{4})$/);
            if (festivalYear) return `${festivalYear[1]}ರ ಹಬ್ಬದ ದರ ದಿನಾಂಕಗಳು`;
            for (const pattern of dynamicPatterns) {
                const match = normalized.match(pattern.english);
                if (match) return pattern.kannada(match);
            }
            return normalized;
        }
        if (english.has(normalized)) return english.get(normalized);
        if (englishFestivalNames.has(normalized)) return englishFestivalNames.get(normalized);
        const festivalYear = normalized.match(/^(\d{4})ರ ಹಬ್ಬದ ದರ ದಿನಾಂಕಗಳು$/);
        if (festivalYear) return `Festival fare dates for ${festivalYear[1]}`;
        for (const pattern of dynamicPatterns) {
            const match = normalized.match(pattern.reverse);
            if (match) return pattern.restore(match);
        }
        return normalized;
    }

    function translateNode(node, language) {
        const value = node.nodeValue;
        const trimmed = value.trim();
        if (!trimmed) return;
        const translated = translate(trimmed, language);
        if (translated !== trimmed) node.nodeValue = value.replace(trimmed, translated);
    }

    function applyLanguage() {
        const language = localStorage.getItem("preferredLanguage") === "kn" ? "kn" : "en";
        document.documentElement.lang = language;
        document.title = translate(document.title, language);

        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            if (!node.parentElement.closest("script, style, noscript")) translateNode(node, language);
        }

        document.querySelectorAll("input[placeholder], textarea[placeholder], [title], [aria-label]").forEach(element => {
            ["placeholder", "title", "aria-label"].forEach(attribute => {
                if (element.hasAttribute(attribute)) {
                    element.setAttribute(attribute, translate(element.getAttribute(attribute), language));
                }
            });
        });
    }

